/**
 * 不同主题对应不同的图标
 * */
export const iconName = (type: string) => {
    switch (type) {
        case 'success':
            return IconConfig.CHECK_CIRCLE
        case 'error':
            return IconConfig.CLOSE_CIRCLE
        case 'warning':
            return IconConfig.ATTENTION
        case 'info':
            return IconConfig.HELP
        case 'primary':
            return IconConfig.COMMENT
        default:
            return IconConfig.CLOSE_CIRCLE
    }
}

